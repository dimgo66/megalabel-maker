/**
 * Генерирует src/config/fallbackFontData.ts — base64 для fallback-шрифта
 * (Roboto Condensed regular/bold), чтобы регистрация шрифта в jsPDF для
 * векторного экспорта не зависела от сети.
 *
 * Зачем: в офисных сетях запросы к /fonts/*.ttf могут падать («Failed to
 * fetch» — прокси/антивирус/медленный канал), и тогда векторная печать
 * сваливается в растр. Если fallback-шрифт вшит в бандл, векторная печать
 * работает всегда (текст рисуется Roboto Condensed вместо недоступного
 * семейства).
 *
 * Запуск: node scripts/embed-fallback-font.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const fontsDir = join(root, 'public', 'fonts');
const out = join(root, 'src', 'config', 'fallbackFontData.ts');

const files = ['RobotoCondensed-Regular.ttf', 'RobotoCondensed-Bold.ttf'];
const parts = [];
for (const f of files) {
  const b64 = readFileSync(join(fontsDir, f)).toString('base64');
  const name = f.replace(/\.ttf$/, '').replace(/[^A-Za-z0-9]/g, '');
  parts.push(`  ${name}: '${b64}',`);
}

const header = `/**
 * AUTOGENERATED — не редактировать вручную (scripts/embed-fallback-font.mjs).
 *
 * base64 fallback-шрифта (Roboto Condensed regular/bold). Вшит в бандл, чтобы
 * векторный экспорт/печать не зависели от сети: если офисная сеть блокирует
 * /fonts/*.ttf, jsPDF всё равно получит шрифт.
 */
export const FALLBACK_FONT_BASE64: Record<'RobotoCondensedRegular' | 'RobotoCondensedBold', string> = {
`;
const body = `${header}${parts.join('\n')}\n};\n`;

writeFileSync(out, body, 'utf8');
console.log(`[embed-font] ${out} (${(body.length / 1024).toFixed(0)} КБ)`);
