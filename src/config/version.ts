/**
 * Версия приложения — единственный источник для интерфейса.
 *
 * Число берётся из `package.json` на сборке (Vite `define: __APP_VERSION__`
 * в `vite.config.js`), поэтому поднимать версию нужно **только там**. Здесь
 * остаётся форматирование для показа: в подписях — «v2.0», в «Справке» —
 * «Megalabel Pro 2.0.0».
 *
 * Почему не импорт `package.json` напрямую: он тянет в бандл весь файл со
 * зависимостями и ломает типизацию `resolveJsonModule`. Подстановка строкой
 * на сборке дешевле и не тянет Node-типы в клиентский код.
 */
declare const __APP_VERSION__: string;

/** Полная версия из package.json, например `2.0.0`. */
export const APP_VERSION: string =
  typeof __APP_VERSION__ === 'string' ? __APP_VERSION__ : '0.0.0';

/**
 * Короткая версия для подписей: `2.0.0` → `2.0`, `2.1.3` → `2.1.3`.
 *
 * Отбрасывается только нулевой патч: значимая правка патча должна быть видна
 * в подписи, иначе две разные сборки выглядят одинаково.
 */
export const APP_VERSION_SHORT: string = APP_VERSION.replace(/\.0$/, '');

/** Название продукта — одно на все подписи. */
export const APP_NAME = 'Megalabel Pro';
